const dictionaries: Record<Lang, Record<TKey, string>> = { en, pl }

function initialLang(): Lang {
  try {
    const v = localStorage.getItem('smartlab.lang')
    return v === 'en' || v === 'pl' ? v : 'pl'
  } catch {
    return 'pl'
  }
}

export const useLang = create<{ lang: Lang; setLang: (l: Lang) => void }>((set) => ({
  lang: initialLang(),
  setLang: (lang) => {
    try {
      localStorage.setItem('smartlab.lang', lang)
    } catch {
      set({ lang })
    }
    document.documentElement.lang = lang
    set({ lang })
  },
}))

export function translate(lang: Lang, key: TKey, params?: Record<string, string | number>): string {
  let s = dictionaries[lang][key] ?? en[key] ?? key
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}

export function t(key: TKey, params?: Record<string, string | number>): string {
  return translate(useLang.getState().lang, key, params)
}

export function tx(key: string, fallback: string): string {
  const lang = useLang.getState().lang
  return (dictionaries[lang] as Record<string, string>)[key] ?? fallback
}

export function useT() {
  const lang = useLang((s) => s.lang)
  return (key: TKey, params?: Record<string, string | number>) => translate(lang, key, params)
}

export function locale(): string {
  return useLang.getState().lang === 'pl' ? 'pl-PL' : 'en-GB'
}

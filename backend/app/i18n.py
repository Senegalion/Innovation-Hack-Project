def get_lang(accept_language: str | None = Header(None)) -> str:
    if accept_language and accept_language.strip().lower().startswith("en"):
        return "en"
    return DEFAULT_LANG


def tr(lang: str, key: str, **params):
    value = T.get(lang, T[DEFAULT_LANG]).get(key, T["en"].get(key, key))
    if isinstance(value, list):
        return [v.format(**params) for v in value]
    return value.format(**params) if params else value


def render(lang: str, tpl: dict | None, field: str, fallback: str) -> str:
    if not tpl or field not in tpl:
        return fallback
    params = {k: (tr(lang, v[4:]) if isinstance(v, str) and v.startswith("key:") else v)
              for k, v in (tpl.get("p") or {}).items()}
    try:
        return tr(lang, tpl[field], **params)
    except (KeyError, IndexError):
        return fallback
